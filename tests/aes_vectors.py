#!/usr/bin/env python3
"""aes_vectors.py OUT.h - AES-128 / AES-128-GCM test vectors (needs the
cryptography package; the generated header is in the repository)"""
import random, sys
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

rnd = random.Random(7)
def rb(n):
    return bytes(rnd.getrandbits(8) for _ in range(n))
def c(b):
    return '{' + ', '.join('0x%02x' % x for x in b) + '}'
out = ['/* generated by tests/aes_vectors.py */',
       'struct vector { uint8_t key[16], nonce[12], pt[64], ecb[16], aad[16], ct[64], tag[16]; uint8_t len, aad_len; };',
       'static const struct vector vec[] = {']
for i, (n, an) in enumerate([(0, 0), (1, 5), (15, 5), (16, 5), (17, 13), (37, 5), (64, 16), (48, 0)]):
    key, nonce, pt, aad = rb(16), rb(12), rb(64), rb(an)
    enc = Cipher(algorithms.AES(key), modes.ECB()).encryptor()
    ecb = enc.update(pt[:16]) + enc.finalize()
    sealed = AESGCM(key).encrypt(nonce, pt[:n], aad)
    out.append('    {%s, %s, %s, %s, %s, %s, %s, %d, %d},' % (
        c(key), c(nonce), c(pt), c(ecb), c(aad + bytes(16 - an)), c(sealed[:n] + bytes(64 - n)),
        c(sealed[n:]), n, an))
out.append('};')
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
