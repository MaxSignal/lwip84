#!/usr/bin/env python3
"""gen_fe_z80.py OUT.s - Z80 field arithmetic mod 2^255-19 for lib/crypto/x25519.c
and the ChaCha20 block function for lib/crypto/chacha.c.

The module is placed alone on a fixed flash page (banker.py fixed@PAGE), so
its tables start at 4000h and are addressed absolutely:

  4000h  38*x, low bytes  (x = 0..255)
  4100h  38*x, high bytes

fe_mul_core computes fe_r = fe_a * fe_b with 4-bit windows: the multiples
1..15 of b are tabulated in the scratch area (fe_scr), then for every byte
of a its low nibble adds a multiple into TL and its high nibble into TH;
finally TL + 16*TH (RLD shifts TH by a nibble) is folded mod p with the
38*x table (2^256 = 38 mod p).  fe_r may alias fe_a or fe_b.

Scratch layout (fe_scr, 627 bytes):
  +0    15 multiples of b, 33 bytes each
  +495  TL, 66 bytes
  +561  TH, 66 bytes
"""
import sys

T38 = 0x4000
V_SIZE = 33
TL_OFF = 15 * V_SIZE
TH_OFF = TL_OFF + 66
SCR_SIZE = TH_OFF + 66

out = []
w = out.append

w(';; generated by tools/gen_fe_z80.py - do not edit')
w('\t.module fe_z80')
w('\t.globl _fe_r, _fe_a, _fe_b, _fe_scr')
w('\t.globl _fe_mul_core, _fe_add_core, _fe_sub_core')
w('FE_SCR_SIZE = %d' % SCR_SIZE)
w('T38LO = 0x%04X' % T38)
w('T38HI = 0x%04X' % (T38 + 0x100))
w('\t.area _DATA')
w('fm_prev:\t.ds 2')
w('fm_i:\t.ds 1')
w('fm_tl:\t.ds 2')
w('fm_th:\t.ds 2')
w('\t.area _CODE')
w('fe_tables::')
for half in (0, 1):
    vals = [((38 * x) >> (8 * half)) & 0xFF for x in range(256)]
    for k in range(0, 256, 16):
        w('\t.db ' + ', '.join('0x%02X' % v for v in vals[k:k + 16]))
# 4200h: more page-aligned tables of other generators (the AES S-box)
if len(sys.argv) > 2:
    out.extend(open(sys.argv[2]).read().splitlines())

# --- add33: (HL) += (DE), 33 bytes, HL/DE advance, carry out in CF
w('fm_add33::')
w('\tor\ta')
for _ in range(V_SIZE):
    w('\tld\ta, (de)')
    w('\tadc\ta, (hl)')
    w('\tld\t(hl), a')
    w('\tinc\tde')
    w('\tinc\thl')
w('\tret\tnc')
# propagate the carry
w('00001$:')
w('\tinc\t(hl)')
w('\tret\tnz')
w('\tinc\thl')
w('\tjr\t00001$')

# --- vaddr: A = m (1..15) -> DE = fe_scr + 33*(m-1)
w('fm_vaddr::')
w('\tdec\ta')
w('\tld\tl, a')
w('\tld\th, #0')
w('\tadd\thl, hl')
w('\tadd\thl, hl')
w('\tadd\thl, hl')
w('\tadd\thl, hl')
w('\tadd\thl, hl')
w('\tld\te, a')
w('\tld\td, #0')
w('\tadd\thl, de')
w('\tld\tde, (_fe_scr)')
w('\tadd\thl, de')
w('\tex\tde, hl')
w('\tret')

w('_fe_mul_core::')
w('\tpush\tix')                    # SDCC's frame pointer
w('\tpush\tiy')
w('\tcall\tfm_mul')
w('\tpop\tiy')
w('\tpop\tix')
w('\tret')
w('fm_mul::')
# TL/TH pointers, clear both
w('\tld\thl, (_fe_scr)')
w('\tld\tde, #%d' % TL_OFF)
w('\tadd\thl, de')
w('\tld\t(fm_tl), hl')
w('\tld\tde, #66')
w('\tex\tde, hl')
w('\tadd\thl, de')
w('\tld\t(fm_th), hl')
w('\tex\tde, hl')            # HL = TL
w('\tld\td, h')
w('\tld\te, l')
w('\tinc\tde')
w('\tld\t(hl), #0')
w('\tld\tbc, #131')
w('\tldir')
# V1 = b
w('\tld\thl, (_fe_b)')
w('\tld\tde, (_fe_scr)')
w('\tld\tbc, #32')
w('\tldir')
w('\txor\ta')
w('\tld\t(de), a')
w('\tld\thl, (_fe_scr)')
w('\tld\t(fm_prev), hl')
# V(m) = V(m-1) + V1, m = 2..15
w('\tld\tb, #14')
w('00010$:')
w('\tpush\tbc')
w('\tld\thl, (fm_prev)')
w('\tld\tde, #33')
w('\tadd\thl, de')
w('\tex\tde, hl')                 # DE = new
w('\tld\thl, (fm_prev)')
w('\tld\t(fm_prev), de')
w('\tld\tbc, #33')
w('\tldir')
w('\tld\thl, (fm_prev)')
w('\tld\tde, (_fe_scr)')
w('\tcall\tfm_add33')
w('\tpop\tbc')
w('\tdjnz\t00010$')
# nibble loop
w('\txor\ta')
w('\tld\t(fm_i), a')
w('00020$:')
w('\tld\thl, (_fe_a)')
w('\tld\ta, (fm_i)')
w('\tld\te, a')
w('\tld\td, #0')
w('\tadd\thl, de')
w('\tld\ta, (hl)')
w('\tpush\taf')
w('\tand\ta, #0x0F')
w('\tjr\tz, 00021$')
w('\tcall\tfm_vaddr')
w('\tld\thl, (fm_tl)')
w('\tld\ta, (fm_i)')
w('\tld\tc, a')
w('\tld\tb, #0')
w('\tadd\thl, bc')
w('\tcall\tfm_add33')
w('00021$:')
w('\tpop\taf')
w('\trrca')
w('\trrca')
w('\trrca')
w('\trrca')
w('\tand\ta, #0x0F')
w('\tjr\tz, 00022$')
w('\tcall\tfm_vaddr')
w('\tld\thl, (fm_th)')
w('\tld\ta, (fm_i)')
w('\tld\tc, a')
w('\tld\tb, #0')
w('\tadd\thl, bc')
w('\tcall\tfm_add33')
w('00022$:')
w('\tld\thl, #fm_i')
w('\tinc\t(hl)')
w('\tld\ta, (hl)')
w('\tcp\ta, #32')
w('\tjr\tc, 00020$')
# TH <<= 4
w('\tld\thl, (fm_th)')
w('\tld\tb, #66')
w('\txor\ta')
w('00030$:')
w('\trld')
w('\tinc\thl')
w('\tdjnz\t00030$')
# TL += TH (66 bytes)
w('\tld\thl, (fm_tl)')
w('\tld\tde, (fm_th)')
w('\tld\tb, #66')
w('\tor\ta')
w('00031$:')
w('\tld\ta, (de)')
w('\tadc\ta, (hl)')
w('\tld\t(hl), a')
w('\tinc\tde')
w('\tinc\thl')
w('\tdjnz\t00031$')
# reduce: r[i] = TL[i] + 38*TL[i+32] + carry
w('\tld\tix, (fm_tl)')
w('\tld\tiy, (_fe_r)')
w('\tld\tbc, #0')
w('\tld\ta, #32')
w('00040$:')
w('\tex\taf, af\'')
w('\tld\tl, 32(ix)')
w('\tld\th, #>T38LO')
w('\tld\te, (hl)')
w('\tinc\th')
w('\tld\td, (hl)')
w('\tld\tl, 0(ix)')
w('\tld\th, #0')
w('\tadd\thl, de')
w('\tadd\thl, bc')
w('\tld\t0(iy), l')
w('\tld\tc, h')
w('\tinc\tix')
w('\tinc\tiy')
w('\tex\taf, af\'')
w('\tdec\ta')
w('\tjr\tnz, 00040$')
# fold the carry C (< 40) times 38, again if it overflows
w('00041$:')
w('\tld\ta, c')
w('\tor\ta, a')
w('\tret\tz')
w('\tld\tl, a')
w('\tld\th, #>T38LO')
w('\tld\te, (hl)')
w('\tinc\th')
w('\tld\td, (hl)')                  # DE = 38 * carry
w('\tld\thl, (_fe_r)')
w('\tld\ta, (hl)')
w('\tadd\ta, e')
w('\tld\t(hl), a')
w('\tinc\thl')
w('\tld\ta, (hl)')
w('\tadc\ta, d')
w('\tld\t(hl), a')
w('\tld\tc, #0')
w('\tld\tb, #30')
w('00042$:')
w('\tjr\tnc, 00041$')
w('\tinc\thl')
w('\tinc\t(hl)')
w('\tscf')
w('\tjr\tnz, 00043$')
w('\tdjnz\t00042$')
w('\tinc\tc')                       # carried out of the top: add 38 again
w('\tjr\t00041$')
w('00043$:')
w('\tret')

# --- fe_add_core: r = a + b, fe_sub_core: r = a - b (both mod p, lazily)
for name, op, fix in (('_fe_add_core', 'adc', 'add'), ('_fe_sub_core', 'sbc', 'sub')):
    w(name + '::')
    w('\tpush\tix')
    w('\tcall\t0%d$' % (60 if op == 'adc' else 70))
    w('\tpop\tix')
    w('\tret')
    w('0%d$:' % (60 if op == 'adc' else 70))
    w('\tld\thl, (_fe_a)')
    w('\tld\tde, (_fe_b)')
    w('\tld\tix, (_fe_r)')
    w('\tld\tb, #32')
    w('\tor\ta, a')
    w('00050$:')
    w('\tld\ta, (hl)')
    w('\tex\tde, hl')
    w('\t%s\ta, (hl)' % op)
    w('\tex\tde, hl')
    w('\tld\t0(ix), a')
    w('\tinc\thl')
    w('\tinc\tde')
    w('\tinc\tix')
    w('\tdjnz\t00050$')
    # carry/borrow out: add/subtract 38 until none
    w('00051$:')
    w('\tret\tnc')
    w('\tld\thl, (_fe_r)')
    w('\tld\ta, (hl)')
    w('\t%s\ta, #38' % fix)
    w('\tld\t(hl), a')
    w('\tld\tb, #31')
    w('00052$:')
    w('\tinc\thl')
    w('\tld\ta, (hl)')
    w('\t%s\ta, #0' % op)
    w('\tld\t(hl), a')
    w('\tdjnz\t00052$')
    w('\tjr\t00051$')

# --- ChaCha20 block: ch_out[64] = ChaCha20(ch_in[16 words]).  The working
# state is at the fixed address ch_x so every word has an absolute address;
# each quarter-round step "p += q; r ^= p; r <<<= n" keeps p and r in BC/DE
# and stores r already rotated (16 and 8 by byte order, 12 = 8 + RLD nibble
# rotation, 7 = 8 then a 1-bit right rotation in registers).
w('\t.area _DATA')
w('ch_x:\t.ds 64')
w('ch_n:\t.ds 1')
w('\t.area _CODE')
w('\t.globl _ch_in, _ch_out, _chacha_block_core')


def X(i, k=0):
    return '(ch_x+%d)' % (4 * i + k)


def step(p, q, r, n):
    w('\tld\thl, %s' % X(p))
    w('\tld\tde, %s' % X(q))
    w('\tadd\thl, de')
    w('\tld\t%s, hl' % X(p))
    w('\tld\tb, h')
    w('\tld\tc, l')
    w('\tld\thl, %s' % X(p, 2))
    w('\tld\tde, %s' % X(q, 2))
    w('\tadc\thl, de')
    w('\tld\t%s, hl' % X(p, 2))
    w('\tld\tde, %s' % X(r))           # DE = r_lo ^ p_lo
    w('\tld\ta, e')
    w('\txor\ta, c')
    w('\tld\te, a')
    w('\tld\ta, d')
    w('\txor\ta, b')
    w('\tld\td, a')
    w('\tld\tbc, %s' % X(r, 2))        # BC = r_hi ^ p_hi
    w('\tld\ta, c')
    w('\txor\ta, l')
    w('\tld\tc, a')
    w('\tld\ta, b')
    w('\txor\ta, h')
    w('\tld\tb, a')
    # value bytes: b0 = E, b1 = D, b2 = C, b3 = B
    if n == 16:
        w('\tld\t%s, bc' % X(r))
        w('\tld\t%s, de' % X(r, 2))
        return
    if n == 7:                          # rotate [b3 b0 b1 b2] right by one bit
        w('\tld\ta, b')
        w('\trra')
        w('\trr\tc')
        w('\trr\td')
        w('\trr\te')
        w('\trr\tb')
    w('\tld\ta, b')                    # store [b3 b0 b1 b2]
    w('\tld\t%s, a' % X(r))
    w('\tld\t%s, de' % X(r, 1))
    w('\tld\ta, c')
    w('\tld\t%s, a' % X(r, 3))
    if n == 12:                         # and rotate left by a nibble
        w('\trrca')
        w('\trrca')
        w('\trrca')
        w('\trrca')
        w('\tld\thl, #%s' % X(r)[1:-1])
        for k in range(4):
            w('\trld')
            if k < 3:
                w('\tinc\thl')


def qr(a, b, c, d):
    step(a, b, d, 16)
    step(c, d, b, 12)
    step(a, b, d, 8)
    step(c, d, b, 7)


w('_chacha_block_core::')
w('\tld\thl, (_ch_in)')
w('\tld\tde, #ch_x')
w('\tld\tbc, #64')
w('\tldir')
w('\tld\ta, #10')
w('00080$:')
w('\tld\t(ch_n), a')
for a, b, c, d in ((0, 4, 8, 12), (1, 5, 9, 13), (2, 6, 10, 14), (3, 7, 11, 15),
                   (0, 5, 10, 15), (1, 6, 11, 12), (2, 7, 8, 13), (3, 4, 9, 14)):
    qr(a, b, c, d)
w('\tld\ta, (ch_n)')
w('\tdec\ta')
w('\tjp\tnz, 00080$')
# x += in (word by word), then copy to out
w('\tld\thl, #ch_x')
w('\tld\tde, (_ch_in)')
w('\tld\tb, #16')
w('00081$:')
w('\tor\ta, a')
for k in range(4):
    w('\tld\ta, (de)')
    w('\tadc\ta, (hl)')
    w('\tld\t(hl), a')
    w('\tinc\tde')
    w('\tinc\thl')
w('\tdjnz\t00081$')
w('\tld\thl, #ch_x')
w('\tld\tde, (_ch_out)')
w('\tld\tbc, #64')
w('\tldir')
w('\tret')

open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
