#!/usr/bin/env python3
"""mknarrow84.py 4x6.bdf OUT.h - Cyrillic and Greek for the SSH terminal
(app/ssh/term.c), whose columns are 4 pixels wide: the glyphs of the public
domain misc-fixed 4x6 font.  Letters drawn like an ASCII letter of that
font become the ASCII letter, letters with an accent their base letter
when they would not fit, the rest get the codes A0h-FEh of a terminal
cell (at most 95 glyphs).  OUT.h has narrow_cp_bk[] (sorted code points),
narrow_to_bk[] (the cell byte for each) and narrow_bk[][3] (rows 0-5, four
pixels each, bit 7 of the first nibble leftmost)."""
import re
import sys
import unicodedata

src = open(sys.argv[1]).read()
glyph = {}
for m in re.finditer(r'ENCODING (\d+)\n.*?BITMAP\n(.*?)ENDCHAR', src, re.S):
    rows = [int(x, 16) >> 4 for x in m.group(2).split()]
    glyph[int(m.group(1))] = tuple((rows + [0] * 6)[:6])

ascii_of = {}
for c in range(0x21, 0x7F):
    if chr(c).isalpha() and c in glyph:
        ascii_of.setdefault(glyph[c], c)

wanted = [c for c in list(range(0x386, 0x3CF)) + list(range(0x400, 0x460))
          if c in glyph and unicodedata.category(chr(c)).startswith('L')]
to = {}                         # code point -> cell byte (ASCII or A0h + n)
shapes = []                     # glyphs of the codes A0h on
first = {}
pending = []
for c in wanted:
    g = glyph[c]
    if g in ascii_of:
        to[c] = ascii_of[g]
    elif g in first:
        to[c] = first[g]
    else:
        pending.append(c)
# letters without accents first, then the rest while codes are left
plain = [c for c in pending if len(unicodedata.normalize('NFD', chr(c))) == 1]
accented = [c for c in pending if c not in plain]
for c in plain + accented:
    g = glyph[c]
    if g in first:
        to[c] = first[g]
    elif len(shapes) < 95:
        first[g] = 0xA0 + len(shapes)
        shapes.append(g)
        to[c] = first[g]
    else:
        base = ord(unicodedata.normalize('NFD', chr(c))[0])
        if base in to:
            to[c] = to[base]
cps = sorted(to)
with open(sys.argv[2], 'w') as f:
    f.write('/* generated by tools/mknarrow84.py from fonts/misc/4x6.bdf (public domain) */\n')
    f.write('#define NARROW_N %d\n' % len(cps))
    f.write('static const uint16_t narrow_cp_bk[NARROW_N] = {\n')
    for i in range(0, len(cps), 10):
        f.write('    ' + ', '.join('0x%04X' % c for c in cps[i:i + 10]) + ',\n')
    f.write('};\nstatic const uint8_t narrow_to_bk[NARROW_N] = {\n')
    for i in range(0, len(cps), 12):
        f.write('    ' + ', '.join('0x%02X' % to[c] for c in cps[i:i + 12]) + ',\n')
    f.write('};\nstatic const uint8_t narrow_bk[%d][3] = {\n' % len(shapes))
    for g in shapes:
        f.write('    {0x%02X, 0x%02X, 0x%02X},\n' % (g[0] << 4 | g[1], g[2] << 4 | g[3], g[4] << 4 | g[5]))
    f.write('};\n')
print('%s: %d letters, %d glyphs' % (sys.argv[2], len(cps), len(shapes)))
