#!/usr/bin/env python3
"""gen_poly1305_z80.py OUT.s - one Poly1305 block in Z80 assembly.

  poly1305_block_core():  h = (h + m + hibit * 2^128) * r  mod (2^130 - 5),
  h (17 bytes, little endian, partially reduced) at *p13_h, r (17 bytes,
  clamped) at *p13_r, m (16 bytes) at *p13_m, hibit in p13_hb.

The multiples 1..15 of r are tabulated once per key (r changes once per
message).  For every byte of h the low nibble adds a multiple into TL and the
high nibble into TH at the byte's position; the product is TL + 16 * TH,
folded with 2^130 = 5 mod p.  Appended to the fixed crypto page.
"""
import sys

out = []
w = out.append

N = 17          # bytes of h and of each multiple
T = 34          # bytes of the accumulators

w(';; generated by tools/gen_poly1305_z80.py - do not edit')
w('\t.globl _p13_h, _p13_r, _p13_m, _p13_hb, _poly1305_block_core')
w('\t.area _DATA')
w('p13_mul:\t.ds %d' % (15 * N))      # r * 1 .. r * 15
w('p13_ptr:\t.ds 32')                  # p13_ptr[k] = &r * k (k = 0 unused)
w('p13_rc:\t.ds 16')                   # r the table belongs to
w('p13_ok:\t.ds 1')
w('p13_tl:\t.ds %d' % T)
w('p13_th:\t.ds %d' % T)
w('\t.area _CODE')


_lbl = [200]


def label():
    _lbl[0] += 1
    return '%05d$' % _lbl[0]


def add_mult(acc):
    """acc[i..] += multiple k: DE = multiple, HL = acc + i; 17 bytes + carry"""
    loop, done, carry = label(), label(), label()
    w('\tld\tb, #%d' % N)
    w('\tor\ta, a')
    w('%s:' % loop)
    w('\tld\ta, (de)')
    w('\tadc\ta, (hl)')
    w('\tld\t(hl), a')
    w('\tinc\tde')
    w('\tinc\thl')
    w('\tdjnz\t%s' % loop)
    w('\tjr\tnc, %s' % done)
    w('%s:' % carry)
    w('\tinc\t(hl)')
    w('\tinc\thl')
    w('\tjr\tz, %s' % carry)
    w('%s:' % done)


w('_poly1305_block_core::')
w('\tpush\tix')
w('\tpush\tiy')
# --- (re)build the table of multiples when r changed
w('\tld\ta, (p13_ok)')
w('\tor\ta, a')
w('\tjr\tz, 00010$')
w('\tld\thl, (_p13_r)')
w('\tld\tde, #p13_rc')
w('\tld\tb, #16')
w('00011$:')
w('\tld\ta, (de)')
w('\tcp\ta, (hl)')
w('\tjr\tnz, 00010$')
w('\tinc\thl')
w('\tinc\tde')
w('\tdjnz\t00011$')
w('\tjp\t00020$')
w('00010$:')
w('\tld\thl, (_p13_r)')
w('\tld\tde, #p13_rc')
w('\tld\tbc, #16')
w('\tldir')
# multiple 1 = r
w('\tld\thl, (_p13_r)')
w('\tld\tde, #p13_mul')
w('\tld\tbc, #%d' % N)
w('\tldir')
# multiple k = multiple k-1 + r, k = 2..15
w('\tld\tix, #p13_mul')            # previous multiple
w('\tld\tc, #14')
w('00012$:')
w('\tld\thl, (_p13_r)')
w('\tld\tb, #%d' % N)
w('\tor\ta, a')
w('\tpush\tix')
w('\tpop\tde')                      # DE = previous
w('00013$:')
w('\tld\ta, (de)')
w('\tadc\ta, (hl)')
w('\tld\t%d (ix), a' % N)           # next = previous + r
w('\tinc\tde')
w('\tinc\thl')
w('\tinc\tix')
w('\tdjnz\t00013$')
w('\tdec\tc')
w('\tjr\tnz, 00012$')
# pointer table
w('\tld\thl, #p13_ptr + 2')
w('\tld\tde, #p13_mul')
w('\tld\tb, #15')
w('00014$:')
w('\tld\t(hl), e')
w('\tinc\thl')
w('\tld\t(hl), d')
w('\tinc\thl')
w('\tpush\thl')
w('\tld\thl, #%d' % N)
w('\tadd\thl, de')
w('\tex\tde, hl')
w('\tpop\thl')
w('\tdjnz\t00014$')
w('\tld\ta, #1')
w('\tld\t(p13_ok), a')
w('00020$:')
# --- h += m + hibit * 2^128
w('\tld\thl, (_p13_h)')
w('\tld\tde, (_p13_m)')
w('\tld\tb, #16')
w('\tor\ta, a')
w('00021$:')
w('\tld\ta, (de)')
w('\tadc\ta, (hl)')
w('\tld\t(hl), a')
w('\tinc\tde')
w('\tinc\thl')
w('\tdjnz\t00021$')
w('\tld\ta, (_p13_hb)')
w('\tadc\ta, (hl)')
w('\tld\t(hl), a')
# --- TL = TH = 0
w('\tld\thl, #p13_tl')
w('\tld\tde, #p13_tl + 1')
w('\tld\tbc, #%d' % (2 * T - 1))
w('\tld\t(hl), #0')
w('\tldir')
# --- nibble products, byte i of h
w('\tld\tix, (_p13_h)')
for i in range(N):
    for half, acc in ((0, 'p13_tl'), (1, 'p13_th')):
        skip = '00%03d$' % (30 + 2 * i + half)
        w('\tld\ta, %d (ix)' % i)
        if half:
            w('\trrca')
            w('\trrca')
            w('\trrca')
            w('\trrca')
        w('\tand\ta, #15')
        w('\tjr\tz, %s' % skip)
        w('\tadd\ta, a')
        w('\tld\te, a')
        w('\tld\td, #0')
        w('\tld\thl, #p13_ptr')
        w('\tadd\thl, de')
        w('\tld\te, (hl)')
        w('\tinc\thl')
        w('\tld\td, (hl)')
        w('\tld\thl, #%s + %d' % (acc, i))
        add_mult(acc)
        w('%s:' % skip)
# --- TH <<= 4 (RLD from the low end), TL += TH
w('\tld\thl, #p13_th')
w('\tld\tb, #%d' % T)
w('\txor\ta, a')
w('00080$:')
w('\trld')
w('\tinc\thl')
w('\tdjnz\t00080$')
w('\tld\thl, #p13_tl')
w('\tld\tde, #p13_th')
w('\tld\tb, #%d' % T)
w('\tor\ta, a')
w('00081$:')
w('\tld\ta, (de)')
w('\tadc\ta, (hl)')
w('\tld\t(hl), a')
w('\tinc\tde')
w('\tinc\thl')
w('\tdjnz\t00081$')
# --- fold: product P in TL (< 2^256).  h = lo + 4*hi + hi, where
#     lo = P mod 2^130, 4*hi = P >> 128 with the low 2 bits cleared,
#     hi = P >> 130.
# hi -> TH[0..16]
w('\tld\tix, #p13_tl + 16')
w('\tld\thl, #p13_th')
for j in range(N):
    w('\tld\ta, %d (ix)' % j)
    w('\tsrl\ta')
    w('\tsrl\ta')
    w('\tld\tc, a')
    w('\tld\ta, %d (ix)' % (j + 1))
    w('\trrca')
    w('\trrca')
    w('\tand\ta, #0xC0')
    w('\tor\ta, c')
    w('\tld\t(hl), a')
    w('\tinc\thl')
# 4*hi -> keep in TL[16..32] with byte 16 & 0xFC; lo byte 16 = TL[16] & 3
w('\tld\ta, (p13_tl + 16)')
w('\tld\tc, a')                      # C = TL[16]
w('\tand\ta, #0xFC')
w('\tld\t(p13_tl + 16), a')
w('\tld\ta, c')
w('\tand\ta, #3')
w('\tld\tc, a')                      # C = lo byte 16
# h = lo + 4*hi + hi
w('\tld\thl, (_p13_h)')
w('\tld\tix, #p13_tl')
w('\tld\tiy, #p13_th')
w('\tor\ta, a')
for j in range(N):
    if j < 16:
        w('\tld\ta, %d (ix)' % j)
    else:
        w('\tld\ta, c')
    w('\tadc\ta, %d (ix)' % (16 + j))
    w('\tld\t(hl), a')
    w('\tinc\thl')
w('\tld\thl, (_p13_h)')
w('\tor\ta, a')
for j in range(N):
    w('\tld\ta, (hl)')
    w('\tadc\ta, %d (iy)' % j)
    w('\tld\t(hl), a')
    w('\tinc\thl')
w('\tpop\tiy')
w('\tpop\tix')
w('\tret')

open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
