#!/usr/bin/env python3
"""gen_aes_z80.py OUT.s [SBOX [SBOX_OUT.s]] - AES-128 block encryption in Z80 assembly.

  aes_encrypt_core():  *aes_out = AES-128(round keys *aes_rk, block *aes_in),
  or, with aes_xor != 0, *aes_out ^= that block (counter mode in place).

The S-box is a page-aligned table at SBOX (default 4200h: in the fixed crypto
page right after the 512-byte table of gen_fe_z80.py, which includes the
table written to SBOX_OUT.s).  Rounds 1-9 are unrolled per column: the four S-box values
of a column (ShiftRows folded into the source addresses) go to B, C, D, E,
MixColumns is

  t = a0^a1^a2^a3,  b_i = a_i ^ t ^ xtime(a_i ^ a_i+1)

with xtime as add/conditional xor, and the round key is added with
(ix+d).  The state alternates between two 16-byte buffers at fixed
addresses, so every load and store is direct.  About 15.5k T-states per
block (about 1000 per byte).  Appended to the fixed crypto page.
"""
import sys

SBOX_DEFAULT = 0x4200


def sbox():
    """the AES S-box, computed from GF(2^8) inverses"""
    def mul(a, b):
        r = 0
        while b:
            if b & 1:
                r ^= a
            a = ((a << 1) ^ 0x11B) if a & 0x80 else a << 1
            b >>= 1
        return r
    inv = [0] * 256
    for a in range(1, 256):
        for b in range(1, 256):
            if mul(a, b) == 1:
                inv[a] = b
                break
    s = []
    for a in range(256):
        x = inv[a]
        y = x
        for _ in range(4):
            x = ((x << 1) | (x >> 7)) & 0xFF
            y ^= x
        s.append(y ^ 0x63)
    return s


def sbox_lines():
    """the table as .db lines (gen_fe_z80.py puts it at 4200h)"""
    s = sbox()
    return ['\t.db ' + ', '.join('0x%02X' % v for v in s[k:k + 16]) for k in range(0, 256, 16)]


def generate(sbox_addr):
    out = []
    w = out.append
    lbl = [300]

    def label():
        lbl[0] += 1
        return '%05d$' % lbl[0]

    w(';; generated by tools/gen_aes_z80.py - do not edit')
    w('\t.globl _aes_rk, _aes_in, _aes_out, _aes_xor, _aes_encrypt_core')
    w('\t.area _DATA')
    w('_aes_rk::\t.ds 2')
    w('_aes_in::\t.ds 2')
    w('_aes_out::\t.ds 2')
    w('_aes_xor::\t.ds 1')
    w('aes_s:\t.ds 16')
    w('aes_t:\t.ds 16')
    w('aes_n:\t.ds 1')
    w('\t.area _CODE')

    regs = ['b', 'c', 'd', 'e']

    def round_(src, dst):
        w('\tld\tde, #16')
        w('\tadd\tix, de')
        for c in range(4):
            for r in range(4):
                w('\tld\ta, (%s + %d)' % (src, r + 4 * ((c + r) % 4)))
                w('\tld\tl, a')
                w('\tld\t%s, (hl)' % regs[r])
            w('\tld\ta, b')
            w('\txor\ta, c')
            w('\txor\ta, d')
            w('\txor\ta, e')
            w('\tld\tl, a')                 # t
            for r in range(4):
                x, y = regs[r], regs[(r + 1) % 4]
                skip = label()
                w('\tld\ta, %s' % x)
                w('\txor\ta, %s' % y)
                w('\tadd\ta, a')
                w('\tjr\tnc, %s' % skip)
                w('\txor\ta, #0x1B')
                w('%s:' % skip)
                w('\txor\ta, l')
                w('\txor\ta, %s' % x)
                w('\txor\ta, %d (ix)' % (4 * c + r))
                w('\tld\t(%s + %d), a' % (dst, 4 * c + r))

    def final(src, xor):
        for c in range(4):
            for r in range(4):
                k = 4 * c + r
                w('\tld\ta, (%s + %d)' % (src, r + 4 * ((c + r) % 4)))
                w('\tld\tl, a')
                w('\tld\ta, (hl)')
                w('\txor\ta, %d (ix)' % k)
                if xor:
                    w('\txor\ta, %d (iy)' % k)
                w('\tld\t%d (iy), a' % k)
        w('\tpop\tiy')
        w('\tpop\tix')
        w('\tret')

    w('_aes_encrypt_core::')
    w('\tpush\tix')
    w('\tpush\tiy')
    w('\tld\tix, (_aes_rk)')
    w('\tld\tiy, (_aes_in)')
    for k in range(16):                     # round 0: AddRoundKey
        w('\tld\ta, %d (iy)' % k)
        w('\txor\ta, %d (ix)' % k)
        w('\tld\t(aes_s + %d), a' % k)
    w('\tld\th, #0x%02X' % (sbox_addr >> 8))
    w('\tld\ta, #4')
    w('\tld\t(aes_n), a')
    loop = label()
    w('%s:' % loop)
    round_('aes_s', 'aes_t')
    round_('aes_t', 'aes_s')
    w('\tld\ta, (aes_n)')
    w('\tdec\ta')
    w('\tld\t(aes_n), a')
    w('\tjp\tnz, %s' % loop)
    round_('aes_s', 'aes_t')                # round 9
    w('\tld\tde, #16')
    w('\tadd\tix, de')                      # round key 10
    w('\tld\tiy, (_aes_out)')
    w('\tld\ta, (_aes_xor)')
    w('\tor\ta, a')
    fx = label()
    w('\tjp\tnz, %s' % fx)
    final('aes_t', False)
    w('%s:' % fx)
    final('aes_t', True)

    # --- GHASH multiplication x = x * H with Shoup's 4-bit table m[16][16]
    #     (m[i] = i * H): per nibble of x, from the last byte, low nibble
    #     first: z = (z >> 4) with the reduction of the 4 bits shifted out,
    #     z ^= m[nibble].  RRD shifts the 16 bytes by a nibble.
    w('\t.area _DATA')
    w('_gh_x::\t.ds 2')
    w('_gh_m::\t.ds 2')
    w('gh_z:\t.ds 16')
    w('gh_p:\t.ds 2')
    w('gh_n:\t.ds 1')
    w('\t.area _CODE')
    w('\t.globl _gh_x, _gh_m, _ghash_mul_core')
    # gh_xor: z ^= m[A]
    w('gh_xor::')
    w('\tadd\ta, a')
    w('\tadd\ta, a')
    w('\tadd\ta, a')
    w('\tadd\ta, a')
    w('\tld\te, a')
    w('\tld\td, #0')
    w('\tld\thl, (_gh_m)')
    w('\tadd\thl, de')
    w('\tld\tde, #gh_z')
    for i in range(16):
        w('\tld\ta, (de)')
        w('\txor\ta, (hl)')
        w('\tld\t(de), a')
        if i < 15:
            w('\tinc\thl')
            w('\tinc\tde')
    w('\tret')
    # gh_shift_xor: z >>= 4 with reduction, then z ^= m[C]
    w('gh_shift_xor::')
    w('\tld\thl, #gh_z')
    w('\txor\ta, a')
    for i in range(16):
        w('\trrd')
        if i < 15:
            w('\tinc\thl')
    # A = the nibble shifted out: z[0..1] ^= last4[A]
    w('\tadd\ta, a')
    w('\tld\te, a')
    w('\tld\td, #0')
    w('\tld\thl, #gh_last4')
    w('\tadd\thl, de')
    w('\tld\ta, (gh_z)')
    w('\txor\ta, (hl)')
    w('\tld\t(gh_z), a')
    w('\tinc\thl')
    w('\tld\ta, (gh_z + 1)')
    w('\txor\ta, (hl)')
    w('\tld\t(gh_z + 1), a')
    w('\tld\ta, c')
    w('\tjp\tgh_xor')
    w('_ghash_mul_core::')
    w('\tld\thl, #gh_z')
    w('\tld\tb, #16')
    w('\txor\ta, a')
    zl = label()
    w('%s:' % zl)
    w('\tld\t(hl), a')
    w('\tinc\thl')
    w('\tdjnz\t%s' % zl)
    w('\tld\thl, (_gh_x)')
    w('\tld\tde, #15')
    w('\tadd\thl, de')
    w('\tld\t(gh_p), hl')
    w('\tld\ta, (hl)')
    w('\tand\ta, #15')
    w('\tcall\tgh_xor')                  # first nibble: z is 0, no shift
    w('\tld\ta, #16')
    w('\tld\t(gh_n), a')
    hi = label()
    w('\tjr\t%s' % hi)
    lp = label()
    w('%s:' % lp)
    w('\tld\thl, (gh_p)')
    w('\tdec\thl')
    w('\tld\t(gh_p), hl')
    w('\tld\ta, (hl)')
    w('\tand\ta, #15')
    w('\tld\tc, a')
    w('\tcall\tgh_shift_xor')
    w('%s:' % hi)
    w('\tld\thl, (gh_p)')
    w('\tld\ta, (hl)')
    w('\trrca')
    w('\trrca')
    w('\trrca')
    w('\trrca')
    w('\tand\ta, #15')
    w('\tld\tc, a')
    w('\tcall\tgh_shift_xor')
    w('\tld\ta, (gh_n)')
    w('\tdec\ta')
    w('\tld\t(gh_n), a')
    w('\tjr\tnz, %s' % lp)
    w('\tld\thl, #gh_z')
    w('\tld\tde, (_gh_x)')
    w('\tld\tbc, #16')
    w('\tldir')
    w('\tret')
    w('gh_last4 = .')
    for v in (0x0000, 0x1c20, 0x3840, 0x2460, 0x7080, 0x6ca0, 0x48c0, 0x54e0,
              0xe100, 0xfd20, 0xd940, 0xc560, 0x9180, 0x8da0, 0xa9c0, 0xb5e0):
        w('\t.db 0x%02X, 0x%02X' % (v >> 8, v & 0xFF))
    return out


if __name__ == '__main__':
    # gen_aes_z80.py OUT.s [SBOX [SBOX_OUT.s]]: SBOX_OUT gets the table
    addr = int(sys.argv[2], 0) if len(sys.argv) > 2 else SBOX_DEFAULT
    if addr & 0xFF:
        sys.exit('gen_aes_z80: the S-box must be page-aligned')
    open(sys.argv[1], 'w').write('\n'.join(generate(addr)) + '\n')
    if len(sys.argv) > 3:
        open(sys.argv[3], 'w').write('\n'.join(sbox_lines()) + '\n')
